export function getProductsForCollection(collectionSlug) {
  return products
    .filter(
      (product) =>
        product.collection === collectionSlug ||
        product.additionalCollections?.includes(collectionSlug)
    )
    .map((product) => ({
      ...product,
      link: `/products/${product.collection}/${product.slug}`,
      img: product.image || product.images?.[0] || "",
    }));
}

export function getProduct(collectionSlug, productSlug) {
  return products.find(
    (product) =>
      product.collection === collectionSlug && product.slug === productSlug
  );
}
